"""
make_repro - turn a falsified assumption into a test the audience runs.

The last link in the trust contract. A finding the audience cannot execute is
still just a reviewer's word, so every confirmed finding ends as a standalone
xUnit project that FAILS while the defect exists and PASSES once it is fixed.

For the #2297 target-framework finding the generated test asserts the thing the
issue actually asked for: that `ExcludeFromCodeCoverage` is applied to generated
code on EVERY framework the library ships. It fails today on netstandard2.0 and
net472 because the guard removes it there.

The test is deliberately readable by a non-expert in ten seconds, because its
job on stage is to be believed.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

CSPROJ = """<Project Sdk="Microsoft.NET.Sdk">
  <PropertyGroup>
    <TargetFramework>net8.0</TargetFramework>
    <Nullable>disable</Nullable>
    <LangVersion>latest</LangVersion>
    <IsPackable>false</IsPackable>
    <AssemblyName>TrustRepro</AssemblyName>
    <RootNamespace>TrustRepro</RootNamespace>
  </PropertyGroup>
  <ItemGroup>
    <PackageReference Include="Microsoft.NET.Test.Sdk" Version="17.11.1" />
    <PackageReference Include="xunit" Version="2.9.2" />
    <PackageReference Include="xunit.runner.visualstudio" Version="2.8.2" />
  </ItemGroup>
</Project>
"""

TEST_CS = '''// GENERATED BY trust/repro/make_repro.py - do not hand-edit.
//
// FINDING UNDER TEST
//   {statement}
//
// WHY THE EXISTING SUITE CANNOT CATCH THIS
//   {invisibility}
//
// VERDICT: {verdict}   SEVERITY: {severity}
//
// This test reads a snapshot of the requested git commit. It needs no network
// and does not build MessagePack: it asserts a property of the templates.
using System;
using System.IO;
using System.Linq;
using Xunit;

namespace TrustRepro;

public class ExcludeFromCodeCoverageAppliesToAllShippedTargets
{{
    // Immutable branch snapshot materialized by make_repro.py
    const string RepoRoot = @"{repo_root}";
    const string TemplateDir = @"src/MessagePack.SourceGenerator/Transforms";

    // Issue #2297 asked for "all generated code" to carry the attribute,
    // unconditionally. The library ships these frameworks:
    static readonly string[] ShippedFrameworks = new[] {{ {shipped} }};

    // The guard the implementation introduced:
    const string Guard = @"{guard}";

    static string[] Templates() => Directory
        .GetFiles(Path.Combine(RepoRoot, TemplateDir), "*.tt",
                  SearchOption.AllDirectories);

    [Fact]
    public void TemplatesExist()
    {{
        Assert.NotEmpty(Templates());
    }}

    [Fact]
    public void AttributeIsNotRestrictedByTargetFramework()
    {{
        var guarded = Templates()
            .Where(f => File.ReadAllText(f).Contains(Guard))
            .Select(Path.GetFileName)
            .OrderBy(x => x)
            .ToArray();

        Assert.True(guarded.Length == 0,
            $"Issue #2297 asked for ExcludeFromCodeCoverage on ALL generated " +
            $"code. {{guarded.Length}} template(s) emit it only when the guard " +
            $"'{{Guard}}' passes, so consumers targeting " +
            $"{{string.Join(", ", ExcludedFrameworks)}} receive no attribute " +
            $"at all, even though the library ships those frameworks " +
            $"({{string.Join(", ", ShippedFrameworks)}}).\\n\\n" +
            $"Templates affected:\\n  {{string.Join("\\n  ", guarded)}}\\n\\n" +
            $"The excluded frameworks are not incompatible: see the compile " +
            $"probe under .trust/probes/, which builds the attribute " +
            $"unguarded on each of them.");
    }}

    static readonly string[] ExcludedFrameworks = new[] {{ {excluded} }};

    [Fact]
    public void ReadmeDoesNotClaimTheAttributeIsUnavailable()
    {{
        var readme = Path.Combine(RepoRoot, "README.md");
        if (!File.Exists(readme)) return;

        var text = File.ReadAllText(readme);
        const string claim = "only emitted for targets where it is available";

        Assert.False(text.Contains(claim, StringComparison.OrdinalIgnoreCase),
            "README.md states the attribute is 'only emitted for targets where " +
            "it is available (not netstandard2.0 or .NET Framework)'. That is " +
            "factually wrong: System.Diagnostics.CodeAnalysis." +
            "ExcludeFromCodeCoverageAttribute exists in netstandard2.0 and in " +
            ".NET Framework 4.0+. The sentence documents a constraint that " +
            "does not exist, and no test in any repository reads a README.");
    }}
}}
'''

README = """# Generated repro - {branch}

Pinned commit: `{commit}`. Sources are copied from that git object into
`source_snapshot/{commit}/`, so switching the working checkout cannot change
the result.

One command:

    dotnet test

## What you should see

Two tests FAIL. That is the point: they assert what issue #2297 actually asked
for, and the current implementation does not deliver it.

| Test | Asserts |
|---|---|
| `AttributeIsNotRestrictedByTargetFramework` | the attribute is applied unconditionally, as the issue requested |
| `ReadmeDoesNotClaimTheAttributeIsUnavailable` | the README does not state a false availability constraint |

`TemplatesExist` passes, which confirms the test is reading the real repository
and not vacuously succeeding.

## Independent check

The finding rests on the excluded frameworks being perfectly capable of the
attribute. Verify that yourself, without trusting this repro:

    {probe}

## What this is NOT

- Not a crash, not data corruption, not a security issue. It is a feature gap
  plus a false sentence in the docs.
- Not a complaint about the whole change. The same agent updated all six
  templates, regenerated 222 snapshots consistently, and kept `.tt`/`.cs` in
  sync. Only the target-framework conditionality is wrong.
- This test detects the guard in template text. The compile probes separately
  establish API availability. It does not compile the full generated output.
"""


def git(repo: Path, *a: str) -> str:
    p = subprocess.run(["git", *a], cwd=repo, capture_output=True, text=True,
                       timeout=120)
    return p.stdout if p.returncode == 0 else ""


def materialize_branch(repo: Path, branch: str, out: Path) -> tuple[Path, str]:
    """Copy only the review inputs from one immutable git commit."""
    commit = git(repo, "rev-parse", "--verify", f"{branch}^{{commit}}").strip()
    if not re.fullmatch(r"[0-9a-f]{40,64}", commit):
        raise ValueError(f"cannot resolve branch {branch!r} to a commit")
    snapshot = out / "source_snapshot" / commit
    snapshot.mkdir(parents=True, exist_ok=True)
    names = git(repo, "ls-tree", "-r", "--name-only", commit, "--",
                "README.md", "src/MessagePack.SourceGenerator/Transforms")
    for name in names.splitlines():
        if name != "README.md" and not (name.startswith(
                "src/MessagePack.SourceGenerator/Transforms/") and
                name.endswith(".tt")):
            continue
        target = snapshot / name
        target.parent.mkdir(parents=True, exist_ok=True)
        p = subprocess.run(["git", "show", f"{commit}:{name}"], cwd=repo,
                           capture_output=True, timeout=120)
        if p.returncode != 0:
            raise ValueError(f"cannot read {name} at {commit}")
        target.write_bytes(p.stdout)
    return snapshot, commit


def pick_finding(ledger: list[dict]) -> dict | None:
    """The highest-severity falsified assumption with a usable guard."""
    cands = [b for b in ledger
             if b.get("assumption", {}).get("verdict") == "FALSIFIED"
             and b.get("assumption", {}).get("cls") == "tfm-guard"]
    if not cands:
        return None
    return max(cands, key=lambda b: b.get("severity") == "moderate")


def main(argv: list[str] | None = None) -> int:
    for s in (sys.stdout, sys.stderr):
        try:
            s.reconfigure(encoding="utf-8", errors="replace")  # type: ignore[attr-defined]
        except (AttributeError, OSError):
            pass

    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--repo", required=True)
    ap.add_argument("--branch", required=True)
    ap.add_argument("--ledger", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--run", action="store_true", help="execute dotnet test now")
    args = ap.parse_args(argv)

    repo = Path(args.repo).resolve()
    ledger = json.loads(Path(args.ledger).read_text(encoding="utf-8"))
    br = pick_finding(ledger)
    if br is None:
        print("no falsified target-framework assumption in the ledger; "
              "nothing to generate")
        return 1

    a = br["assumption"]
    guard = ""
    m = re.search(r"#if (.+)$", a.get("source_ref", ""), re.M)
    if m:
        guard = f"#if {m.group(1).strip()}"
    if not guard:
        print("could not recover the guard text from the ledger")
        return 1

    excluded = [s["ref"] for s in br.get("sites", [])
                if s["kind"] == "target_framework"]
    sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "assumptions"))
    import tfm_guard_check as tg
    shipped = tg.read_tfms(repo, args.branch, ["src/"])

    invis = ("no test project targets the excluded frameworks, and the 222 "
             "verified snapshots were regenerated WITH the guard, so the "
             "snapshot tests now assert the narrowed output is correct"
             if br.get("test_invisible") else
             "the existing suite may partially cover this")

    out = Path(args.out).resolve()
    out.mkdir(parents=True, exist_ok=True)
    try:
        snapshot, commit = materialize_branch(repo, args.branch, out)
    except ValueError as exc:
        print(exc)
        return 1
    (out / "TrustRepro.csproj").write_text(CSPROJ, encoding="utf-8")
    (out / "ExcludeFromCodeCoverageTests.cs").write_text(TEST_CS.format(
        statement=a["statement"].replace("\n", " "),
        invisibility=invis,
        verdict=a["verdict"], severity=br.get("severity", "unknown"),
        repo_root=str(snapshot).replace('"', '""'),
        shipped=", ".join(f'"{t}"' for t in shipped),
        excluded=", ".join(f'"{t}"' for t in excluded),
        guard=guard,
    ), encoding="utf-8")
    (out / "README.md").write_text(README.format(
        branch=args.branch, commit=commit,
        probe=a.get("check_cmd", "(see .trust/probes/)"),
    ), encoding="utf-8")

    print(f"generated repro in {out}")
    print(f"  pinned commit    : {commit}")
    print(f"  guard under test : {guard}")
    print(f"  shipped tfms     : {', '.join(shipped)}")
    print(f"  excluded tfms    : {', '.join(excluded)}")
    print(f"\n  run it:  cd {out} && dotnet test")

    if args.run:
        print("\n" + "=" * 70)
        exe = tg.dotnet_exe()
        if exe is None:
            print("  .NET SDK not found; run `dotnet test` yourself in the "
                  "directory above")
            return 2
        p = subprocess.run([exe, "test", str(out / "TrustRepro.csproj"),
                            "--nologo", "-v", "q"],
                           capture_output=True, text=True, timeout=900)
        tail = (p.stdout + p.stderr).strip().splitlines()
        for line in tail[-28:]:
            print("  " + line)
        print("=" * 70)
        print(f"  dotnet test exit code: {p.returncode} "
              f"({'FAILED as expected' if p.returncode else 'PASSED - finding may be fixed'})")
        if p.returncode == 0 or "AttributeIsNotRestrictedByTargetFramework" not in p.stdout + p.stderr:
            return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
